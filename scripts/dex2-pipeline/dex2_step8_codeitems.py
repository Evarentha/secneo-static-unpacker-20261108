UNUSED = set([0x3e,0x3f,0x40,0x41,0x42,0x43,0x73,0x79,0x7a] + list(range(0xe3,0xfa)))

def validate_stream(start, units):
    """return True iff the entire stream decodes with legal opcodes and ends exactly."""
    o, end = start, start + 2*units
    while o < end:
        if o + 2 > end: return False
        w = struct.unpack_from("<H", data, o)[0]
        op = w & 0xff
        if w == 0:                     # nop
            o += 2; continue
        if w == 0x0100:                # packed-switch-payload
            if o + 4 > end: return False
            size = struct.unpack_from("<H", data, o+2)[0]
            o += 2*(4 + 2*size)
            continue
        if w == 0x0200:                # sparse-switch-payload
            if o + 4 > end: return False
            size = struct.unpack_from("<H", data, o+2)[0]
            o += 2*(2 + 4*size)
            continue
        if w == 0x0300:                # fill-array-data-payload
            if o + 8 > end: return False
            esize, n = struct.unpack_from("<HI", data, o+2)
            total = 2*(4 + (n*esize + 1)//2)
            o += total
            continue
        if op in UNUSED: return False
        o += 2*(1 + SZ[op])
    return o == end

def scan_chunk(lo, hi):
    found = []
    for h in range(lo if lo % 4 == 0 else lo + (4-lo % 4), hi, 4):
        if h + 16 > N: break
        regs, ins, outs, tries, dbg, units = struct.unpack_from("<HHHHII", data, h)
        if not (1 <= regs <= 255) or ins > regs or outs > 63: continue
        if tries > 16: continue
        if not (1 <= units <= 30000): continue
        if dbg and dbg >= N: continue
        if h + 16 + 2*units > N: continue
        if validate_stream(h+16, units):
            found.append((h, regs, ins, outs, tries, dbg, units))
    return found

code_items = []
CH = 0x40000
for base in range(TAIL, N, CH):
    end = min(base+CH, N)
    r = scan_chunk(base, end)
    code_items += r
    print(f"  chunk {base:#08x}-{end:#08x}: {len(r)} validated code_items (total {len(code_items)})")
json.dump(code_items, open("unpack/out/dex2_code_items.json","w"))
